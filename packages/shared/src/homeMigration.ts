// @effect-diagnostics nodeBuiltinImport:off - Node-only migration runs before either app's runtime and before Electron may yield.
import * as NodeFS from "node:fs";
import * as NodePath from "node:path";
import * as NodeSqlite from "node:sqlite";
import * as NodeWorkerThreads from "node:worker_threads";

export const PAPERPLANE_HOME_NAME = ".paperplane";
export const HOME_MIGRATION_REPORT = "home-migration.json";

// Copy userdata: conversations, attachments, credentials, preferences, browser
// profiles, logs, and desktop state. Copy scratch and projects: they are user work.
// Preserve unknown entries too, rather than silently losing user-owned files.
const skippedEntries = new Map([
  ["worktrees", "Git worktrees and stored absolute paths must stay at their original locations."],
  [
    "runtime",
    "Downloaded runtimes and service processes must be rebuilt by installed-state migration (3c).",
  ],
  ["caches", "Provider caches are rebuilt."],
  ["dev", "Development state is disposable and is not migrated."],
  ["tools", "Downloaded browser, provider, and device tools are rebuilt."],
  ["bin", "Desktop CLI shims are regenerated; old shims and PATH ownership belong to 3c."],
  ["ssh-launch", "SSH launch scripts and process discovery are regenerated by 3c."],
  ["wsl-runtime", "WSL runtime downloads are rebuilt by 3c."],
  ["userdata/server-owner.sqlite", "The old server's ownership lock must never be copied."],
  ["userdata/server-runtime.json", "The old server's process discovery is transient."],
  ["userdata/agent-pids", "Old agent process identities are transient."],
  ["userdata/agent-hook", "Old agent hook endpoints are transient."],
  ["userdata/opencode-servers", "Old OpenCode server endpoints are transient."],
]);

export interface HomeMigrationStep {
  readonly name: string;
  /** Only mutate this staged home. Never open the old home for writing. */
  readonly run: (stagedHome: string) => void;
}

export interface HomeMigrationReport {
  readonly source: string;
  readonly destination: string;
  readonly completedAt: string;
  readonly copied: string[];
  readonly skipped: { path: string; reason: string }[];
  readonly databases: string[];
  readonly steps: string[];
}

export type HomeMigrationOutcome =
  | {
      readonly kind: "skipped";
      readonly reason: "explicit-home" | "development" | "destination-exists" | "source-missing";
    }
  | { readonly kind: "migrated"; readonly report: HomeMigrationReport };

export class HomeMigrationError extends Error {
  override readonly name = "HomeMigrationError";
}

const exists = (path: string): boolean => {
  try {
    NodeFS.lstatSync(path);
    return true;
  } catch (error) {
    if (error instanceof Error && "code" in error && error.code === "ENOENT") return false;
    throw error;
  }
};

const isBusy = (error: unknown) =>
  error instanceof Error && "errcode" in error && (error.errcode === 5 || error.errcode === 6);

/** A read transaction conflicts with the old server's BEGIN EXCLUSIVE without writing its lock file. */
function lockOldServer(source: string): NodeSqlite.DatabaseSync | undefined {
  const path = NodePath.join(source, "userdata", "server-owner.sqlite");
  if (!exists(path)) return undefined;
  const database = new NodeSqlite.DatabaseSync(path, { readOnly: true });
  try {
    database.exec("PRAGMA busy_timeout = 0; BEGIN; SELECT count(*) FROM sqlite_schema;");
    return database;
  } catch (error) {
    database.close();
    if (isBusy(error)) {
      throw new HomeMigrationError(
        "Quit Rove Code and stop the rove background service, then start Paperplane again. " +
          `A running Rove Code server holds ${path}; the home has not been migrated.`,
      );
    }
    throw error;
  }
}

/**
 * Electron must finish migration before its pre-ready settings and Clerk setup,
 * without yielding. The worker owns the async backup API; Atomics.wait blocks
 * only this one-time startup. No subprocess, external Node, or bundle file is needed.
 */
export function backupHomeDatabase(source: string, destination: string): void {
  // SQLite's read-only connections can still update WAL read marks in the
  // source -shm file. Give the reader a private WAL/SHM namespace instead.
  // Hard-link the main file, never copy its bytes, and open that alias read-only.
  // Only backup() creates the destination database. The old-server lock keeps
  // the source stable while its WAL is copied. EXDEV fails safely for mounts.
  const snapshotDirectory = NodeFS.mkdtempSync(
    NodePath.join(NodePath.dirname(destination), ".sqlite-backup-"),
  );
  const snapshotSource = NodePath.join(snapshotDirectory, "source.sqlite");
  try {
    NodeFS.linkSync(source, snapshotSource);
    for (const suffix of ["-wal", "-journal"]) {
      if (exists(source + suffix)) NodeFS.copyFileSync(source + suffix, snapshotSource + suffix);
    }
    backupIsolatedDatabase(snapshotSource, destination);
  } finally {
    NodeFS.rmSync(snapshotDirectory, { recursive: true, force: true });
  }
}

function backupIsolatedDatabase(source: string, destination: string): void {
  const signal = new Int32Array(new SharedArrayBuffer(4));
  const { port1, port2 } = new NodeWorkerThreads.MessageChannel();
  const worker = new NodeWorkerThreads.Worker(
    `const { workerData } = require('node:worker_threads');
    (async () => {
      const NodeSqlite = require('node:sqlite');
      const database = new NodeSqlite.DatabaseSync(workerData.source, { readOnly: true });
      try { await NodeSqlite.backup(database, workerData.destination); }
      finally { database.close(); }
    })().then(
      () => workerData.port.postMessage(null),
      error => workerData.port.postMessage(String(error && error.stack || error))
    ).finally(() => {
      workerData.port.close();
      Atomics.store(workerData.signal, 0, 1);
      Atomics.notify(workerData.signal, 0);
    });`,
    {
      eval: true,
      // Do not inherit a launcher's --input-type=module into this CommonJS worker.
      execArgv: [],
      workerData: { source, destination, signal, port: port2 },
      transferList: [port2],
    },
  );
  worker.unref();
  try {
    // A broken worker must fail startup, never hang Electron indefinitely.
    if (Atomics.wait(signal, 0, 0, 300_000) === "timed-out") {
      void worker.terminate();
      throw new HomeMigrationError(`Timed out taking a read-only SQLite snapshot of ${source}.`);
    }
    const message = NodeWorkerThreads.receiveMessageOnPort(port1);
    if (message === undefined || message.message !== null) {
      throw new HomeMigrationError(`Could not snapshot ${source}: ${String(message?.message)}`);
    }
  } finally {
    port1.close();
  }
}

function isDatabase(path: string): boolean {
  if (/\.(sqlite3?|db)$/i.test(path)) return true;
  const file = NodeFS.openSync(path, "r");
  try {
    const header = Buffer.alloc(16);
    return (
      NodeFS.readSync(file, header, 0, 16, 0) === 16 && header.toString() === "SQLite format 3\0"
    );
  } finally {
    NodeFS.closeSync(file);
  }
}

function copyEntry(
  source: string,
  staged: string,
  relative: string,
  report: HomeMigrationReport,
): void {
  const reason = skippedEntries.get(relative);
  if (reason !== undefined) {
    report.skipped.push({ path: relative, reason });
    return;
  }
  const from = NodePath.join(source, relative);
  const to = NodePath.join(staged, relative);
  const stat = NodeFS.lstatSync(from);
  if (stat.isSymbolicLink()) {
    // Keep links as links; never follow them into the old home or outside it.
    NodeFS.symlinkSync(NodeFS.readlinkSync(from), to);
  } else if (stat.isDirectory()) {
    NodeFS.mkdirSync(to, { mode: 0o700 });
    for (const name of NodeFS.readdirSync(from).sort()) {
      copyEntry(source, staged, `${relative}/${name}`, report);
    }
    NodeFS.chmodSync(to, stat.mode & 0o777);
  } else if (stat.isFile()) {
    const databasePath = from.replace(/-(wal|shm|journal)$/, "");
    if (databasePath !== from && exists(databasePath) && isDatabase(databasePath)) {
      report.skipped.push({
        path: relative,
        reason: "SQLite sidecars are folded into the backup snapshot.",
      });
      return;
    }
    if (isDatabase(from)) {
      backupHomeDatabase(from, to);
      report.databases.push(relative);
    } else {
      NodeFS.copyFileSync(from, to, NodeFS.constants.COPYFILE_EXCL);
    }
    NodeFS.chmodSync(to, stat.mode & 0o777);
  } else {
    report.skipped.push({
      path: relative,
      reason: "Sockets and other process-local special files are not durable state.",
    });
  }
}

/** Call before resolving or opening a default home. All filesystem roots are explicit, including in tests. */
export function migrateDefaultHome(input: {
  readonly homeDirectory: string;
  readonly explicitHome?: string | undefined;
  readonly development?: boolean | undefined;
  /** Ordered staged transformations, e.g. 3b's database link rewrites. */
  readonly steps?: readonly HomeMigrationStep[] | undefined;
  readonly log?: (message: string) => void;
}): HomeMigrationOutcome {
  if (input.explicitHome?.trim()) return { kind: "skipped", reason: "explicit-home" };
  if (input.development) return { kind: "skipped", reason: "development" };
  const source = NodePath.join(input.homeDirectory, ".rove-code");
  const destination = NodePath.join(input.homeDirectory, PAPERPLANE_HOME_NAME);
  if (exists(destination)) return { kind: "skipped", reason: "destination-exists" };
  if (!exists(source)) return { kind: "skipped", reason: "source-missing" };

  // This stable inode serializes simultaneous CLI/desktop migrations and makes
  // stale-stage removal safe after a crash. Never unlink a SQLite lock file.
  const guard = new NodeSqlite.DatabaseSync(
    NodePath.join(input.homeDirectory, ".paperplane-migration.sqlite"),
  );
  let oldOwner: NodeSqlite.DatabaseSync | undefined;
  const staged = NodePath.join(input.homeDirectory, ".paperplane-migration-stage");
  try {
    try {
      guard.exec("PRAGMA busy_timeout = 0; BEGIN EXCLUSIVE;");
    } catch (error) {
      if (isBusy(error))
        throw new HomeMigrationError(
          "Another Paperplane home migration is running. Start Paperplane again after it finishes.",
        );
      throw error;
    }
    if (exists(destination)) return { kind: "skipped", reason: "destination-exists" };
    oldOwner = lockOldServer(source);
    NodeFS.rmSync(staged, { recursive: true, force: true });
    NodeFS.mkdirSync(staged, { mode: 0o700 });
    const report: HomeMigrationReport = {
      source,
      destination,
      // @effect-diagnostics-next-line globalDate:off - this pre-runtime module has no Effect clock.
      completedAt: new Date().toISOString(),
      copied: [],
      skipped: [],
      databases: [],
      steps: [],
    };
    const pipeline: readonly HomeMigrationStep[] = [
      {
        name: "copy-user-state",
        run: (stagedHome) => {
          for (const entry of NodeFS.readdirSync(source).sort()) {
            copyEntry(source, stagedHome, entry, report);
            if (!skippedEntries.has(entry)) report.copied.push(entry);
          }
        },
      },
      ...(input.steps ?? []),
    ];
    for (const step of pipeline) {
      step.run(staged);
      report.steps.push(step.name);
    }
    NodeFS.writeFileSync(
      NodePath.join(staged, HOME_MIGRATION_REPORT),
      JSON.stringify(report, null, 2) + "\n",
      { mode: 0o600, flag: "wx" },
    );
    NodeFS.chmodSync(staged, NodeFS.statSync(source).mode & 0o777);
    // The migration guard serializes publishers. Recheck immediately before the
    // single same-filesystem rename, including destinations created during steps.
    if (exists(destination)) return { kind: "skipped", reason: "destination-exists" };
    NodeFS.renameSync(staged, destination);
    const log =
      input.log ?? ((message: string) => process.stderr.write(`[home-migration] ${message}\n`));
    log(
      `Copied ${report.copied.join(", ")} from ${source} to ${destination}. The old home is kept as a backup.`,
    );
    for (const entry of report.skipped) log(`Skipped ${entry.path}: ${entry.reason}`);
    return { kind: "migrated", report };
  } finally {
    // A crash leaves the stage for the next lock owner to remove. Ordinary
    // failures do too, so an active migration's stage is never removed here.
    oldOwner?.close();
    guard.close();
  }
}
