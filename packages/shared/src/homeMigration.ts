export const rewriteSavedDataStep: HomeMigrationStep = {
  name: "paperplane-saved-data",
  run: (stagedHome) => {
    const visit = (directory: string) => {
      for (const entry of NodeFS.readdirSync(directory, { withFileTypes: true })) {
        const path = NodePath.join(directory, entry.name);
        if (entry.isDirectory()) {
          // Browser profiles, provider credentials, logs and attachment bytes are opaque.
          if (
            ![
              "browser",
              "browser-profiles",
              "secrets",
              "logs",
              "attachments",
              "providers",
            ].includes(entry.name)
          )
            visit(path);
        } else if (entry.isFile() && isDatabase(path)) {
          rewriteStagedDatabase(path);
        } else if (entry.isFile() && savedJsonFiles.has(entry.name)) {
          const raw = NodeFS.readFileSync(path, "utf8");
          // Invalid app-owned JSON fails the stage instead of silently publishing unmigrated data.
          const next =
            JSON.stringify(rewriteSavedToolNames(migrateSavedAppJson(decodeJson(raw))), null, 2) +
            "\n";
          if (next !== raw) NodeFS.writeFileSync(path, next);
        }
      }
    };
    visit(stagedHome);
  },
};

/** Only the legacy-name lookup lives here. Callers accept no upstream cookie aliases. */
export function previousPaperplaneCookieNames(
  cookieName: string,
  unscopedName?: string,
  instanceKey?: string,
): string[] {
  const previous = (name: string) =>
    name.replace(/^paperplane(?=_(?:session(?:_|$)|dev_session_))/, "rove");
  const hash = (key: string) =>
    NodeCrypto.createHash("sha256").update(key).digest("hex").slice(0, 12);
  const oldInstance = instanceKey?.replace(/([/\\])\.paperplane(?=[/\\]|$)/, "$1.rove-code");
  const movedHomeCookie =
    instanceKey !== undefined &&
    oldInstance !== undefined &&
    oldInstance !== instanceKey &&
    cookieName.endsWith(`_${hash(instanceKey)}`)
      ? previous(cookieName).replace(new RegExp(`${hash(instanceKey)}$`), hash(oldInstance))
      : undefined;
  return [
    ...new Set([
      previous(cookieName),
      movedHomeCookie,
      unscopedName,
      unscopedName === undefined ? undefined : previous(unscopedName),
    ]),
  ].filter((name): name is string => name !== undefined && name !== cookieName);
}

/** A committed report permanently bars new migrations; an exclusive lock excludes a publisher still finishing. */
export function cleanupHomeMigrationGuard(homeDirectory: string): void {
  const report = NodePath.join(homeDirectory, PAPERPLANE_HOME_NAME, HOME_MIGRATION_REPORT);
  const path = NodePath.join(homeDirectory, ".paperplane-migration.sqlite");
  if (!exists(report) || !exists(path)) return;
  // Validate the commit marker before retiring the shared lock. Never follow a symlink.
  if (!NodeFS.lstatSync(report).isFile() || !NodeFS.lstatSync(path).isFile()) return;
  decodeReport(NodeFS.readFileSync(report, "utf8"));
  const guard = new NodeSqlite.DatabaseSync(path, { open: true });
  let acquired = false;
  try {
    guard.exec("PRAGMA busy_timeout = 0; BEGIN EXCLUSIVE;");
    acquired = true;
  } catch (error) {
    if (!isBusy(error)) throw error;
  } finally {
    guard.close();
  }
  if (!acquired) return;
  // Every process that passed the initial report check rechecks it under the
  // lock before touching the stage. After the report exists no owner can migrate,
  // including a late opener of a new inode. Windows requires closing before unlink.
  for (const suffix of ["-journal", "-wal", "-shm", ""])
    NodeFS.rmSync(path + suffix, { force: true });
}

type RefMigrationResult = { converted: number; conflicts: string[] };
const repositoryRefMigrations = new Map<string, Promise<RefMigrationResult>>();
let checkpointRefMigrationEnabled = false;

/**
 * Arms the lazy ref conversion when the serving home was migrated from Rove Code.
 * Other homes (tests, worktree dev state, fresh installs) leave refs alone: their
 * repositories can still belong to a running Rove Code install, which reads only
 * `refs/rove/*`.
 */
export function enableCheckpointRefMigration(baseDir: string): void {
  try {
    const report = NodeFS.readFileSync(NodePath.join(baseDir, HOME_MIGRATION_REPORT), "utf8");
    checkpointRefMigrationEnabled = decodeReport(report).status === "migrated";
  } catch {
    checkpointRefMigrationEnabled = false;
  }
}

/**
 * Lazy conversion of `refs/rove/*` to `refs/paperplane/*`, once per path per process,
 * before the first Git operation there. Only the first caller gets the result;
 * later callers wait for it and get nothing new. A failure moves no ref and
 * retries on the next start. Never call this from home migration: the old
 * version may still own those refs.
 */
export async function migrateRepositoryCheckpointRefs(cwd: string): Promise<RefMigrationResult> {
  if (!checkpointRefMigrationEnabled) return { converted: 0, conflicts: [] };
  const pending = repositoryRefMigrations.get(cwd);
  if (pending !== undefined) {
    await pending.catch(() => {});
    return { converted: 0, conflicts: [] };
  }
  const migration = convertRepositoryCheckpointRefs(cwd);
  repositoryRefMigrations.set(cwd, migration);
  return migration;
}

async function convertRepositoryCheckpointRefs(cwd: string): Promise<RefMigrationResult> {
  const git = (args: string[], input = "") =>
    new Promise<string>((resolve, reject) => {
      const child = NodeChildProcess.execFile(
        "git",
        args,
        { cwd, encoding: "utf8", timeout: 20_000, maxBuffer: 32 * 1024 * 1024 },
        (error, stdout) => (error ? reject(error) : resolve(stdout.trim())),
      );
      // Git can exit before reading its input; the callback reports that failure.
      child.stdin?.on("error", () => {});
      child.stdin?.end(input);
    });
  // CAS on both sides makes concurrent callers from linked worktrees safe: the
  // loser's transaction fails, and its retry finds nothing left to move.
  for (let attempt = 0; ; attempt++) {
    const listed = await git([
      "for-each-ref",
      "--format=%(refname) %(objectname) %(symref)",
      "refs/rove/",
      "refs/paperplane/",
    ]);
    const refs = new Map(
      listed
        .split("\n")
        .filter(Boolean)
        .map((line) => {
          const [name = "", oid = "", ...symbolic] = line.split(" ");
          return [name, { oid, symbolic: symbolic.join(" ").trim() }] as const;
        }),
    );
    const conflicts: string[] = [];
    const commands = ["start", "option no-deref"];
    let converted = 0;
    for (const [name, ref] of refs) {
      if (!name.startsWith("refs/rove/")) continue;
      const target = name.replace(/^refs\/rove\//, "refs/paperplane/");
      const current = refs.get(target);
      const symbolicUsers = [...refs.values()].some((entry) => entry.symbolic === name);
      if (
        ref.symbolic ||
        symbolicUsers ||
        current?.symbolic ||
        (current !== undefined && current.oid !== ref.oid)
      ) {
        conflicts.push(`${name} -> ${target}`);
        continue;
      }
      commands.push(
        current === undefined ? `create ${target} ${ref.oid}` : `verify ${target} ${ref.oid}`,
      );
      commands.push(`delete ${name} ${ref.oid}`);
      converted++;
    }
    if (converted === 0) return { converted, conflicts };
    commands.push("prepare", "commit", "");
    try {
      await git(["-c", "core.fsync=reference", "update-ref", "--stdin"], commands.join("\n"));
      return { converted, conflicts };
    } catch (error) {
      if (attempt >= 2) throw error;
    }
  }
}

export class PaperplaneCookieMigrationError extends Schema.TaggedError<PaperplaneCookieMigrationError>()(
  "PaperplaneCookieMigrationError",
  { cause: Schema.Defect() },
) {}

/** Attach the handoff to whichever authenticated HTTP endpoint received the old cookie. */
export function handoffPaperplaneCookie(input: {
  request: HttpServerRequest.HttpServerRequest;
  cookieName: string;
  unscopedName?: string | undefined;
  instanceKey?: string | undefined;
  token: string;
  expiresAt: DateTime.DateTime;
}) {
  const previous = previousPaperplaneCookieNames(
    input.cookieName,
    input.unscopedName,
    input.instanceKey,
  ).filter((name) => input.request.cookies[name] !== undefined);
  if (previous.length === 0) return Effect.void;
  const options = { httpOnly: true, path: "/", sameSite: "lax" } as const;
  return Effect.gen(function* () {
    let cookies = yield* Effect.fromResult(
      Cookies.set(Cookies.empty, input.cookieName, input.token, {
        ...options,
        expires: DateTime.toDate(input.expiresAt),
      }),
    );
    for (const name of previous)
      cookies = yield* Effect.fromResult(Cookies.expireCookie(cookies, name, options));
    yield* HttpEffect.appendPreResponseHandler((_request, response) =>
      Effect.succeed(
        HttpServerResponse.setHeaders(HttpServerResponse.mergeCookies(response, cookies), {
          "cache-control": "no-store",
          pragma: "no-cache",
        }),
      ),
    );
  }).pipe(
    Effect.mapError((cause) => new PaperplaneCookieMigrationError({ cause })),
    Effect.provideService(HttpServerRequest.HttpServerRequest, input.request),
  );
}

/** Read old Chromium origins without registering them or opening their profile in Electron. */
export function prepareDesktopStorageMigration<E, R>(input: {
  userDataPath: string;
  appDataDirectory: string;
  development: boolean;
  read: (directory: string, origin: string) => Effect.Effect<ReadonlyMap<string, string>, E, R>;
}) {
  const marker = NodePath.join(input.userDataPath, "paperplane-local-storage-imported");
  const complete = Effect.try(() => NodeFS.writeFileSync(marker, "", { mode: 0o600 })).pipe(
    Effect.catch((cause) =>
      Effect.logWarning("Could not record the desktop storage conversion.", cause),
    ),
  );
  return Effect.gen(function* () {
    if (exists(marker)) return undefined;
    const origin = `${input.development ? "rove-dev" : "rove"}://app`;
    const profiles = [input.userDataPath];
    if (!exists(NodePath.join(input.userDataPath, "v1-local-storage-imported"))) {
      profiles.push(
        NodePath.join(input.appDataDirectory, input.development ? "rove-code-dev" : "rove-code"),
      );
    }
    const items: Record<string, string> = {};
    for (const profile of profiles) {
      const directory = NodePath.join(profile, "Local Storage", "leveldb");
      if (!exists(directory)) continue;
      const entries = yield* input.read(directory, origin);
      for (const [key, value] of entries) {
        // Per-install identity must not be shared with the retired V1 client.
        if (profile !== input.userDataPath && key === "rove.backgroundActivity.clientId") continue;
        const next = key.replace(/^rove(?=[.:])/, "paperplane");
        if (!(next in items)) items[next] = migrateStoredClientValue(value, next);
      }
    }
    return { items, complete };
  });
}
