export type HomeMigrationOutcome =
  | {
      readonly kind: "skipped";
      readonly reason: "explicit-home" | "development" | "destination-exists" | "source-missing";
    }
  | {
      readonly kind: "skipped";
      readonly reason: "destination-userdata-exists";
      readonly report: typeof skippedReport.Type;
    }
  | { readonly kind: "migrated"; readonly report: typeof migratedReport.Type };

