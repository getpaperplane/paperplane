const exists = (path: string): boolean => {
  try {
    NodeFS.lstatSync(path);
    return true;
  } catch (error) {
    if (error instanceof Error && "code" in error && error.code === "ENOENT") return false;
    throw error;
  }
};

const isBusy = (error: unknown) =>
  error instanceof Error && "errcode" in error && (error.errcode === 5 || error.errcode === 6);

/** A read transaction conflicts with the old server's BEGIN EXCLUSIVE without writing its lock file. */
function lockOldServer(source: string): NodeSqlite.DatabaseSync | undefined {
  const path = NodePath.join(source, "userdata", "server-owner.sqlite");
  if (!exists(path)) return undefined;
  const database = new NodeSqlite.DatabaseSync(path, { readOnly: true });
  try {
    database.exec("PRAGMA busy_timeout = 0; BEGIN; SELECT count(*) FROM sqlite_schema;");
    return database;
  } catch (error) {
    database.close();
    if (isBusy(error)) {
      throw new HomeMigrationError(
        "Quit Rove Code and stop the rove background service, then start Paperplane again. " +
          `A running Rove Code server holds ${path}; the home has not been migrated.`,
      );
    }
    throw error;
  }
}

/**
 * Electron must finish migration before its pre-ready settings and Clerk setup,
 * without yielding. The worker owns the async backup API; Atomics.wait blocks
 * only this one-time startup. No subprocess, external Node, or bundle file is needed.
 */
export function backupHomeDatabase(source: string, destination: string): void {
  // SQLite's read-only connections can still update WAL read marks in the
  // source -shm file. Give the reader a private WAL/SHM namespace instead.
  // Hard-link the main file, never copy its bytes, and open that alias read-only.
  // Only backup() creates the destination database. The old-server lock keeps
  // the source stable while its WAL is copied. EXDEV fails safely for mounts.
  const snapshotDirectory = NodeFS.mkdtempSync(
    NodePath.join(NodePath.dirname(destination), ".sqlite-backup-"),
  );
  const snapshotSource = NodePath.join(snapshotDirectory, "source.sqlite");
  try {
    NodeFS.linkSync(source, snapshotSource);
    for (const suffix of ["-wal", "-journal"]) {
      if (exists(source + suffix)) NodeFS.copyFileSync(source + suffix, snapshotSource + suffix);
    }
    backupIsolatedDatabase(snapshotSource, destination);
  } finally {
    NodeFS.rmSync(snapshotDirectory, { recursive: true, force: true });
  }
}

function backupIsolatedDatabase(source: string, destination: string): void {
  const signal = new Int32Array(new SharedArrayBuffer(4));
  const { port1, port2 } = new NodeWorkerThreads.MessageChannel();
  const worker = new NodeWorkerThreads.Worker(
    `const { workerData } = require('node:worker_threads');
    (async () => {
      const NodeSqlite = require('node:sqlite');
      const database = new NodeSqlite.DatabaseSync(workerData.source, { readOnly: true });
      try { await NodeSqlite.backup(database, workerData.destination); }
      finally { database.close(); }
    })().then(
      () => workerData.port.postMessage(null),
      error => workerData.port.postMessage(String(error && error.stack || error))
    ).finally(() => {
      workerData.port.close();
      Atomics.store(workerData.signal, 0, 1);
      Atomics.notify(workerData.signal, 0);
    });`,
    {
      eval: true,
      // Do not inherit a launcher's --input-type=module into this CommonJS worker.
      execArgv: [],
      workerData: { source, destination, signal, port: port2 },
      transferList: [port2],
    },
  );
  worker.unref();
  try {
    // A broken worker must fail startup, never hang Electron indefinitely.
    if (Atomics.wait(signal, 0, 0, 300_000) === "timed-out") {
      void worker.terminate();
      throw new HomeMigrationError(`Timed out taking a read-only SQLite snapshot of ${source}.`);
    }
    const message = NodeWorkerThreads.receiveMessageOnPort(port1);
    if (message === undefined || message.message !== null) {
      throw new HomeMigrationError(`Could not snapshot ${source}: ${String(message?.message)}`);
    }
  } finally {
    port1.close();
  }
}

function isDatabase(path: string): boolean {
  if (/\.(sqlite3?|db)$/i.test(path)) return true;
  const file = NodeFS.openSync(path, "r");
  try {
    const header = Buffer.alloc(16);
    return (
      NodeFS.readSync(file, header, 0, 16, 0) === 16 && header.toString() === "SQLite format 3\0"
    );
  } finally {
    NodeFS.closeSync(file);
  }
}

/** A single native rename which cannot replace even an empty destination directory. */
export function publishHomeMigration(
  staged: string,
  destination: string,
): "published" | "destination-exists" {
  // Load the existing native binding only for a migration, never on no-op starts.
  const Ffi: typeof import("ffi-rs") = requireNative("ffi-rs");
  // oxlint-disable-next-line paperplane/no-global-process-runtime -- This adapter must call the actual host kernel's rename API.
  const platform = NodeOS.platform();
  let libraryPath: string;
  if (platform === "win32") libraryPath = "kernel32.dll";
  else if (platform === "darwin") libraryPath = "/usr/lib/libSystem.B.dylib";
  else if (platform === "linux") {
    // Resolve the already-loaded libc, including musl, rather than assuming a
    // distribution's soname or architecture-specific installation directory.
    const mappedLibc = NodeFS.readFileSync("/proc/self/maps", "utf8")
      .split("\n")
      .map((line) => line.trim().split(/\s+/).at(-1))
      .find(
        (path) =>
          path !== undefined && /\/(?:libc[^/]*\.so(?:\.\d+)*|ld-musl-[^/]*\.so\.\d+)$/.test(path),
      );
    if (mappedLibc === undefined)
      throw new HomeMigrationError(
        "Could not locate libc for an exclusive home rename. The old home is unchanged.",
      );
    libraryPath = mappedLibc;
  } else
    throw new HomeMigrationError(
      `Exclusive home migration is not supported on ${platform}. The old home is unchanged.`,
    );

  const library = "paperplane-home-migration";
  Ffi.open({ library, path: libraryPath });
  try {
    const result =
      platform === "win32"
        ? Ffi.load<DataType.I32, true>({
            library,
            funcName: "MoveFileExW",
            retType: Ffi.DataType.I32,
            paramsType: [Ffi.DataType.WString, Ffi.DataType.WString, Ffi.DataType.U32],
            // No REPLACE_EXISTING or COPY_ALLOWED: publish only with one rename.
            paramsValue: [staged, destination, 0],
            errno: true,
          })
        : platform === "darwin"
          ? Ffi.load<DataType.I32, true>({
              library,
              funcName: "renamex_np",
              retType: Ffi.DataType.I32,
              paramsType: [Ffi.DataType.String, Ffi.DataType.String, Ffi.DataType.U32],
              paramsValue: [staged, destination, 0x4],
              errno: true,
            }) // RENAME_EXCL
          : Ffi.load<DataType.I32, true>({
              library,
              funcName: "renameat2",
              retType: Ffi.DataType.I32,
              paramsType: [
                Ffi.DataType.I32,
                Ffi.DataType.String,
                Ffi.DataType.I32,
                Ffi.DataType.String,
                Ffi.DataType.U32,
              ],
              paramsValue: [-100, staged, -100, destination, 1],
              errno: true,
            }); // AT_FDCWD, RENAME_NOREPLACE
    if (platform === "win32" ? result.value !== 0 : result.value === 0) return "published";
    if (exists(destination)) return "destination-exists";
    throw new HomeMigrationError(
      `Could not exclusively publish ${destination}: ${result.errnoMessage}. The old home is unchanged.`,
    );
  } finally {
    Ffi.close(library);
  }
}

function copyEntry(source: string, staged: string, relative: string, report: CopyReport): void {
  const reason = skippedEntries.get(relative);
  if (reason !== undefined) {
    report.skipped.push({ path: relative, reason });
    return;
  }
  const from = NodePath.join(source, relative);
  const to = NodePath.join(staged, relative);
  const stat = NodeFS.lstatSync(from);
  if (stat.isSymbolicLink()) {
    // Keep links as links; never follow them into the old home or outside it.
    NodeFS.symlinkSync(NodeFS.readlinkSync(from), to);
  } else if (stat.isDirectory()) {
    NodeFS.mkdirSync(to, { mode: 0o700 });
    for (const name of NodeFS.readdirSync(from).sort()) {
      copyEntry(source, staged, `${relative}/${name}`, report);
    }
    NodeFS.chmodSync(to, stat.mode & 0o777);
  } else if (stat.isFile()) {
    const databasePath = from.replace(/-(wal|shm|journal)$/, "");
    if (databasePath !== from && exists(databasePath) && isDatabase(databasePath)) {
      report.skipped.push({
        path: relative,
        reason: "SQLite sidecars are folded into the backup snapshot.",
      });
      return;
    }
    if (isDatabase(from)) {
      backupHomeDatabase(from, to);
      report.databases.push(relative);
    } else {
      NodeFS.copyFileSync(from, to, NodeFS.constants.COPYFILE_EXCL);
    }
    NodeFS.chmodSync(to, stat.mode & 0o777);
  } else {
    report.skipped.push({
      path: relative,
      reason: "Sockets and other process-local special files are not durable state.",
    });
  }
}

/** Replace only our private journal; the public report is always published without replacement. */
function stageReport(staged: string, report: HomeMigrationReport): void {
  const next = `${staged}-report-next`;
  NodeFS.rmSync(next, { force: true });
  NodeFS.writeFileSync(next, JSON.stringify(report, null, 2) + "\n", {
    mode: 0o600,
    flag: "wx",
  });
  NodeFS.renameSync(next, NodePath.join(staged, HOME_MIGRATION_REPORT));
}

function destinationIsOccupied(destination: string): boolean {
  // Do not traverse a redirected home, even if its target is missing.
  return exists(destination) && !NodeFS.lstatSync(destination).isDirectory();
}

function userDataConflict(report: HomeMigrationReport): typeof skippedReport.Type {
  return {
    ...report,
    status: "skipped",
    reason: "destination-userdata-exists",
    copied: [],
    databases: [],
    skipped: [
      {
        path: ".",
        reason:
          "The old home was not migrated because the destination already contains userdata. The homes were not merged.",
      },
    ],
  };
}

function finishMigration(
  staged: string,
  destination: string,
  prepared: HomeMigrationReport,
): HomeMigrationReport | undefined {
  // The usual case still publishes the entire home with a single rename.
  if (publishHomeMigration(staged, destination) === "published") return prepared;
  if (
    destinationIsOccupied(destination) ||
    exists(NodePath.join(destination, HOME_MIGRATION_REPORT))
  )
    return undefined;
  // The source home may be read-only. Only the single-rename publication
  // inherits that mode; entry publication needs a writable private stage.
  NodeFS.chmodSync(staged, 0o700);

  let report = prepared;
  if (report.status === "migrated") {
    // userdata goes first. Its absence from a prepared stage proves it was
    // published by this migration, so a retry must retain it, including newer
    // writes. If it is still staged, destination userdata belongs to another
    // install and must never be merged.
    if (
      exists(NodePath.join(destination, "userdata")) &&
      (!report.copied.includes("userdata") || exists(NodePath.join(staged, "userdata")))
    ) {
      report = userDataConflict(report);
    } else {
      const entries = [
        ...report.copied.filter((entry) => entry === "userdata"),
        ...report.copied.filter((entry) => entry !== "userdata"),
      ];
      for (const entry of entries) {
        const from = NodePath.join(staged, entry);
        if (!exists(from)) continue; // Already published before an interruption.
        if (publishHomeMigration(from, NodePath.join(destination, entry)) === "published") continue;
        if (entry === "userdata") {
          report = userDataConflict(report);
          break;
        }
        report = {
          ...report,
          copied: report.copied.filter((path) => path !== entry),
          databases: report.databases.filter(
            (path) => !path.startsWith(`${entry}/`) && path !== entry,
          ),
          skipped: [
            ...report.skipped,
            { path: entry, reason: "The destination entry already exists and was left untouched." },
          ],
        };
      }
    }
  }
  // Conflicting entries remain in the stage until this commit. A crash can
  // repeat their no-replace checks without mistaking them for published data.
  stageReport(staged, report);
  if (
    publishHomeMigration(
      NodePath.join(staged, HOME_MIGRATION_REPORT),
      NodePath.join(destination, HOME_MIGRATION_REPORT),
    ) === "destination-exists"
  )
    return undefined;
  NodeFS.rmSync(staged, { recursive: true, force: true });
  return report;
}

/** Call before resolving or opening a default home. All filesystem roots are explicit, including in tests. */
export function migrateDefaultHome(input: {
  readonly homeDirectory: string;
  readonly explicitHome?: string | undefined;
  readonly development?: boolean | undefined;
  /** Ordered staged transformations, e.g. 3b's database link rewrites. */
  readonly steps?: readonly HomeMigrationStep[] | undefined;
  readonly log?: (message: string) => void;
}): HomeMigrationOutcome {
  if (input.explicitHome?.trim()) return { kind: "skipped", reason: "explicit-home" };
  if (input.development) return { kind: "skipped", reason: "development" };
  const source = NodePath.join(input.homeDirectory, ".rove-code");
  const destination = NodePath.join(input.homeDirectory, PAPERPLANE_HOME_NAME);
  const reportPath = NodePath.join(destination, HOME_MIGRATION_REPORT);
  if (destinationIsOccupied(destination)) return { kind: "skipped", reason: "destination-exists" };
  if (exists(reportPath)) {
    cleanupHomeMigrationGuard(input.homeDirectory);
    return { kind: "skipped", reason: "destination-exists" };
  }
  if (!exists(source)) return { kind: "skipped", reason: "source-missing" };

  // This stable inode serializes simultaneous CLI/desktop migrations and makes
  // stale-stage removal safe after a crash. Never unlink a SQLite lock file.
  const guard = new NodeSqlite.DatabaseSync(
    NodePath.join(input.homeDirectory, ".paperplane-migration.sqlite"),
  );
  let oldOwner: NodeSqlite.DatabaseSync | undefined;
  const staged = NodePath.join(input.homeDirectory, ".paperplane-migration-stage");
  try {
    try {
      guard.exec("PRAGMA busy_timeout = 0; BEGIN EXCLUSIVE;");
    } catch (error) {
      if (isBusy(error))
        throw new HomeMigrationError(
          "Another Paperplane home migration is running. Start Paperplane again after it finishes.",
        );
      throw error;
    }
    if (destinationIsOccupied(destination) || exists(reportPath))
      return { kind: "skipped", reason: "destination-exists" };
    let prepared: HomeMigrationReport;
    const stagedReport = NodePath.join(staged, HOME_MIGRATION_REPORT);
    if (exists(stagedReport)) {
      prepared = decodeReport(NodeFS.readFileSync(stagedReport, "utf8"));
      if (prepared.source !== source || prepared.destination !== destination)
        throw new HomeMigrationError(
          `The staged migration at ${staged} belongs to a different home.`,
        );
    } else {
      const progress: CopyReport = { skipped: [], databases: [], steps: [] };
      const initial = {
        source,
        destination,
        // @effect-diagnostics-next-line globalDate:off - this pre-runtime module has no Effect clock.
        completedAt: new Date().toISOString(),
        copied: [],
        ...progress,
      };
      if (exists(NodePath.join(destination, "userdata"))) {
        prepared = userDataConflict({ ...initial, status: "migrated" });
        NodeFS.rmSync(staged, { recursive: true, force: true });
        NodeFS.mkdirSync(staged, { mode: 0o700 });
      } else {
        oldOwner = lockOldServer(source);
        // Only an unprepared stage can be discarded. A prepared stage may
        // already have published entries, and is the retry journal.
        NodeFS.rmSync(staged, { recursive: true, force: true });
        NodeFS.mkdirSync(staged, { mode: 0o700 });
        const pipeline: readonly HomeMigrationStep[] = [
          {
            name: "copy-user-state",
            run: (stagedHome) => {
              for (const entry of NodeFS.readdirSync(source).sort())
                copyEntry(source, stagedHome, entry, progress);
            },
          },
          rewriteSavedDataStep,
          ...(input.steps ?? []),
        ];
        for (const step of pipeline) {
          step.run(staged);
          progress.steps.push(step.name);
        }
        if (exists(stagedReport))
          throw new HomeMigrationError(`Migration steps must not write ${HOME_MIGRATION_REPORT}.`);
        prepared = {
          ...initial,
          status: "migrated",
          copied: NodeFS.readdirSync(staged).sort(),
        };
      }
      stageReport(staged, prepared);
      if (prepared.status === "migrated")
        NodeFS.chmodSync(staged, NodeFS.statSync(source).mode & 0o777);
    }
    if (prepared.status === "migrated" && oldOwner === undefined) oldOwner = lockOldServer(source);
    const report = finishMigration(staged, destination, prepared);
    if (report === undefined) return { kind: "skipped", reason: "destination-exists" };
    const log =
      input.log ?? ((message: string) => process.stderr.write(`[home-migration] ${message}\n`));
    if (report.status === "skipped") {
      log(
        `The old home ${source} was not migrated: ${destination} already contains userdata. See ${reportPath}.`,
      );
      return { kind: "skipped", reason: report.reason, report };
    }
    log(
      `Copied ${report.copied.join(", ")} from ${source} to ${destination}. The old home is kept as a backup.`,
    );
    for (const entry of report.skipped) log(`Skipped ${entry.path}: ${entry.reason}`);
    return { kind: "migrated", report };
  } finally {
    // A prepared stage survives failures and process death for the next owner
    // to finish. Unprepared copying is restarted by the next lock owner.
    oldOwner?.close();
    guard.close();
  }
}

// All server-side saved-data conversions are confined to this deletable pipeline.
const oldMcpServers = new Set(["rove", "rove-code", "rove_code"]);
const oldMcpTools = new Map(
  [...PAPERPLANE_MCP_TOOL_NAMES, "computer_describe", "computer_call"].map((name) => [
    name.replace(/^paperplane_/, "rove_"),
    name,
  ]),
);

/** Match whole tool identifiers only, never mentions in messages, arguments or output. */
function rewriteSavedToolIdentifier(value: string): string {
  const bare = oldMcpTools.get(value);
  if (bare !== undefined) return bare;
  const mcp = /^mcp__(rove|rove-code|rove_code)__(.+)$/i.exec(value);
  const namespaced = /^(rove|rove-code|rove_code)(?:[.:/]| · )(.+)$/i.exec(value);
  const prefixed = /^(?:mcp[-_]{1,2})?rove(?:[-_ ]?code)?[-_.:/ ]{1,3}(.+)$/i.exec(value);
  const candidate = mcp?.[2] ?? namespaced?.[2] ?? prefixed?.[1];
  const tool = candidate === undefined ? undefined : oldMcpTools.get(candidate);
  if (tool !== undefined) return `mcp__paperplane__${tool}`;
  // OpenCode registers an injected server per thread; keep that server's suffix.
  if (/^rove-/i.test(value)) {
    for (const [old, next] of [...oldMcpTools].sort((a, b) => b[0].length - a[0].length)) {
      if (value.endsWith(`_${old}`)) {
        const server = value.slice(0, -(old.length + 1));
        if (/^rove-[\w:-]+$/i.test(server)) return `paperplane-${server.slice(5)}_${next}`;
      }
    }
  }
  return value;
}

const toolIdentityKeys = new Set(["toolName", "tool_name", "tool"]);
const mcpServerKeys = new Set(["server", "serverName", "server_name", "mcpServer", "mcp_server"]);
const opaqueToolKeys = new Set([
  "input",
  "output",
  "arguments",
  "args",
  "params",
  "parameters",
  "toolInput",
  "toolOutput",
  "rawInput",
  "rawOutput",
]);
const nativeToolTypes = new Set(["tool_use", "function_call", "mcp_tool_call"]);

function rewriteSavedToolNames(value: Schema.Json): Schema.Json {
  if (Arr.isArray<Schema.Json>(value)) return value.map(rewriteSavedToolNames);
  if (value === null || typeof value !== "object") return value;
  const server =
    value.server ?? value.serverName ?? value.server_name ?? value.mcpServer ?? value.mcp_server;
  const foreignServer =
    typeof server === "string" &&
    !oldMcpServers.has(server.toLowerCase()) &&
    !/^rove-[\w:-]+$/i.test(server);
  const nativeTool = typeof value.type === "string" && nativeToolTypes.has(value.type);
  const hasToolIdentity = [
    value.toolName,
    value.tool_name,
    value.tool,
    nativeTool ? value.name : null,
  ].some(
    (name) =>
      typeof name === "string" &&
      (oldMcpTools.has(name) || rewriteSavedToolIdentifier(name) !== name),
  );
  return Object.fromEntries(
    Object.entries(value).map(([key, entry]) => {
      if (typeof entry === "string") {
        if (hasToolIdentity && mcpServerKeys.has(key) && oldMcpServers.has(entry.toLowerCase()))
          return [key, "paperplane"];
        if (hasToolIdentity && mcpServerKeys.has(key) && /^rove-[\w:-]+$/i.test(entry))
          return [key, `paperplane-${entry.slice(5)}`];
        if (!foreignServer && (toolIdentityKeys.has(key) || (key === "name" && nativeTool))) {
          return [key, rewriteSavedToolIdentifier(entry)];
        }
        return [key, entry];
      }
      return [key, opaqueToolKeys.has(key) ? entry : rewriteSavedToolNames(entry)];
    }),
  );
}

const quoteSqlIdentifier = (name: string) => `"${name.replaceAll('"', '""')}"`;
const decodeJson = Schema.decodeUnknownSync(Schema.fromJsonString(Schema.Json));

/** Enumerate the staged schema, including V1, V2, outbox, attachments, PR and future JSON columns. */
export function rewriteStagedDatabase(
  path: string,
): { table: string; column: string; rows: number }[] {
  const database = new NodeSqlite.DatabaseSync(path);
  const changed: { table: string; column: string; rows: number }[] = [];
  try {
    database.function("paperplane_links", (value) => {
      if (typeof value !== "string") return value;
      const next = migrateSavedAppJson(value);
      return typeof next === "string" ? next : value;
    });
    database.function("paperplane_json", (value) => {
      if (typeof value !== "string") return value;
      try {
        return JSON.stringify(rewriteSavedToolNames(migrateSavedAppJson(decodeJson(value))));
      } catch {
        return rewriteSavedLinks(value);
      }
    });
    database.function("paperplane_tool", (value) =>
      typeof value === "string" ? rewriteSavedToolIdentifier(value) : value,
    );
    database.function("paperplane_mcp_server", (value) =>
      typeof value === "string" && oldMcpServers.has(value.toLowerCase()) ? "paperplane" : value,
    );
    database.exec("BEGIN IMMEDIATE");
    const tables = database
      .prepare("SELECT name FROM sqlite_schema WHERE type = 'table' AND name NOT LIKE 'sqlite_%'")
      .all();
    for (const table of tables) {
      if (typeof table.name !== "string") continue;
      const name = quoteSqlIdentifier(table.name);
      const columns = database.prepare(`PRAGMA table_xinfo(${name})`).all();
      const toolTable = columns.some(
        (column) => typeof column.name === "string" && toolIdentityKeys.has(column.name),
      );
      for (const column of columns) {
        if (typeof column.name !== "string" || column.hidden !== 0) continue;
        const field = quoteSqlIdentifier(column.name);
        const transform = column.name.endsWith("_json")
          ? "paperplane_json"
          : toolIdentityKeys.has(column.name)
            ? "paperplane_tool"
            : toolTable && mcpServerKeys.has(column.name)
              ? "paperplane_mcp_server"
              : "paperplane_links";
        const result = database
          .prepare(
            `UPDATE ${name} SET ${field} = ${transform}(${field}) WHERE typeof(${field}) = 'text' AND instr(lower(${field}), 'rove') > 0 AND ${field} != ${transform}(${field})`,
          )
          .run();
        if (result.changes)
          changed.push({ table: table.name, column: column.name, rows: Number(result.changes) });
      }
    }
    database.exec("COMMIT");
    return changed;
  } finally {
    database.close();
  }
}

